"""Stage 0: expand seed terms into query clusters (mock by default).

Usage:
  python -m pipeline.waist_expand --seeds config/seeds.yaml --out exports/waist_expanded.json
  python -m pipeline.waist_expand --seeds config/seeds.yaml --provider mock
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover
    yaml = None  # type: ignore


def _load_seeds(path: Path) -> list[str]:
    if not path.is_file():
        raise FileNotFoundError(path)
    text = path.read_text(encoding="utf-8")
    if path.suffix in (".yaml", ".yml"):
        if yaml is None:
            raise RuntimeError("PyYAML required to read YAML seeds; pip install pyyaml")
        data = yaml.safe_load(text) or {}
        seeds: list[str] = []
        for block in (data.values() if isinstance(data, dict) else []):
            if isinstance(block, dict):
                seeds.extend(str(s) for s in block.get("seeds") or [])
            elif isinstance(block, list):
                seeds.extend(str(s) for s in block)
        return sorted({s.strip() for s in seeds if str(s).strip()})
    return [ln.strip() for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]


def expand_mock(seeds: list[str]) -> dict[str, Any]:
    """Deterministic stub; replace with LLM via prompts/waist_expand.md."""
    clusters = []
    for i, seed in enumerate(seeds[:12]):
        slug = seed.lower().replace(" ", "-")[:48]
        clusters.append(
            {
                "id": f"cluster-{i}-{slug}",
                "label": seed,
                "queries": [
                    f"{seed} alternatives",
                    f"{seed} vs",
                    f"{seed} pricing",
                ],
                "spike_risk_notes": "mock — run LLM stage 0 for real clusters",
            }
        )
    return {
        "as_of": date.today().isoformat(),
        "provider": "mock",
        "seeds": seeds,
        "clusters": clusters,
        "comparison_queries": [f"{s} alternatives" for s in seeds[:8]],
        "pricing_queries": [f"{s} pricing" for s in seeds[:8]],
        "long_tail_modifiers": ["benchmark", "calculator", "how to"],
        "skip_brand_or_news": [],
        "notes": "Generated by pipeline/waist_expand.py mock. Wire OpenAI/Cursor for production.",
    }


def expand_openai_stub(seeds: list[str]) -> dict[str, Any]:
    """Placeholder: load prompt and call API when key present."""
    out = expand_mock(seeds)
    out["provider"] = "openai_stub"
    out["notes"] = (
        "OpenAI provider not implemented in-repo. Use prompts/waist_expand.md in Composer "
        "and save JSON to --out manually."
    )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Stage 0 waist keyword expansion (mock)")
    parser.add_argument("--seeds", type=Path, default=Path("config/seeds.yaml"))
    parser.add_argument("--out", type=Path, default=Path("exports/waist_expanded.json"))
    parser.add_argument(
        "--provider",
        choices=["mock", "openai"],
        default="mock",
        help="mock (default) or openai (stub only)",
    )
    args = parser.parse_args(argv)

    seeds = _load_seeds(args.seeds)
    if args.provider == "openai":
        payload = expand_openai_stub(seeds)
    else:
        payload = expand_mock(seeds)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"status": "ok", "out": str(args.out), "seed_count": len(seeds)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
